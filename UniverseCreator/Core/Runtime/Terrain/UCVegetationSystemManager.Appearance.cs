// UC-T06-09: appearance invalidation has its own authority; it never schedules graph evaluation.
using System;
using UnityEngine;

namespace UniverseCreator.TerrainSystem
{
    public partial class UCVegetationSystemManager
    {
        private long placementRevision = 1, appearanceRevision = 1;

        /// <summary>Runtime count of placement-input invalidations; appearance-only requests leave it unchanged.</summary>
        public long PlacementRevision => placementRevision;
        /// <summary>Runtime appearance request revision, independent of accepted graph/placement revisions.</summary>
        public long AppearanceRevision => appearanceRevision;

        /// <summary>Invalidates seasonal appearance, requests bounded native colour/material refresh and republishes shared season globals without rebuilding placement.</summary>
        /// <remarks>Main thread only. A world with no accepted terrain has nothing to refresh and is never generated by this request.</remarks>
        /// <exception cref="OverflowException">The runtime revision counter is exhausted.</exception>
        public void MarkAppearanceDirty()
        {
            appearanceRevision = checked(appearanceRevision + 1);
            seasonSolvesValid = false; // UC-T08-04: clock/weather appearance refresh cannot reuse a previous day's solved season.
            var world = World;
            if (world != null && world.Chunks != null) world.Chunks.RequestVegetationAppearance();
            if (isActiveAndEnabled && vegetationEnabled) PublishShaderGlobals();
        }
    }
}
